#!/usr/bin/env python3
"""Create new RL parquet files with explicit strict five-subgraph prompts.

The source parquet files are never modified.  Every user prompt must contain
the historical abstract ``<Subgraph_i>`` block exactly once; it is replaced
with five concrete blocks generated by the current prompt template.
"""

import argparse
import os
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd


REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from data_generation.pipelines.prompt_templete import PromptTemplete  # noqa: E402


ABSTRACT_BLOCK = re.compile(
    r"<Subgraph_i>\(i start from index 0\)\n.*?</Subgraph_i>\n",
    re.DOTALL,
)
SAMPLING_REASON_LINE = "  - Explain the reason for sampling each subgraph.\n"
STRICT_NUMBERING_LINE = (
    "  - The final structured answer must contain exactly 5 complete "
    "subgraph blocks numbered consecutively from 0 to 4.\n"
)


def upgrade_content(content):
    """Replace one abstract candidate block and add the strict numbering rule."""
    explicit_blocks = PromptTemplete().answer_format_subgraph_sampling_prompt(5)
    upgraded, replacement_count = ABSTRACT_BLOCK.subn(explicit_blocks, content)
    if replacement_count != 1:
        raise ValueError(
            "Expected exactly one abstract <Subgraph_i> answer block, "
            f"found {replacement_count}"
        )
    if STRICT_NUMBERING_LINE not in upgraded:
        if SAMPLING_REASON_LINE not in upgraded:
            raise ValueError("Sampling-reason instruction was not found")
        upgraded = upgraded.replace(
            SAMPLING_REASON_LINE,
            SAMPLING_REASON_LINE + STRICT_NUMBERING_LINE,
            1,
        )
    for subgraph_id in range(5):
        if upgraded.count(f"<Subgraph_{subgraph_id}>") != 1:
            raise ValueError(f"Prompt does not contain one <Subgraph_{subgraph_id}> block")
        if upgraded.count(f"</Subgraph_{subgraph_id}>") != 1:
            raise ValueError(f"Prompt does not contain one </Subgraph_{subgraph_id}> block")
    return upgraded


def upgrade_messages(messages):
    upgraded_messages = []
    user_message_count = 0
    for message in messages:
        copied = dict(message)
        if copied.get("role") == "user":
            copied["content"] = upgrade_content(copied["content"])
            user_message_count += 1
        upgraded_messages.append(copied)
    if user_message_count != 1:
        raise ValueError(f"Expected exactly one user message, got {user_message_count}")
    return np.array(upgraded_messages, dtype=object)


def upgrade_parquet(source, destination):
    source = Path(source).resolve()
    destination = Path(destination).resolve()
    if source == destination:
        raise ValueError("Source and destination must differ")
    if destination.exists():
        raise FileExistsError(f"Destination already exists: {destination}")

    frame = pd.read_parquet(source)
    frame["prompt"] = [upgrade_messages(messages) for messages in frame["prompt"]]

    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(destination.suffix + ".tmp")
    frame.to_parquet(temporary, index=False)
    os.replace(temporary, destination)
    return len(frame)


def parse_args():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("destination", type=Path)
    return parser.parse_args()


def main():
    args = parse_args()
    row_count = upgrade_parquet(args.source, args.destination)
    print(f"Wrote {row_count} strict SSR prompts to {args.destination.resolve()}")


if __name__ == "__main__":
    main()
